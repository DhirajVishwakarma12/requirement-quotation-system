const router = require('express').Router();
const c = require('../controllers/projectController');
const { protect, allow } = require('../middleware/auth');
router.use(protect);
router.get('/', c.listProjects);
router.get('/suggestions/:level', c.getSuggestions);
router.get('/developers', allow('admin'), c.listDevelopers);
router.get('/:id/budget-suggestions', allow('client'), c.getBudgetMessageSuggestions);
router.post('/', allow('client'), c.createProject);
router.get('/:id', c.getProject);
router.patch('/:id/counter-offer', allow('admin'), c.sendCounterOffer);
router.patch('/:id/client-counter-offer', allow('client'), c.sendClientCounterOffer);
router.post('/:id/budget/confirm', allow('client', 'admin'), c.confirmBudgetOffer);
router.post('/:id/developer', allow('admin'), c.assignDeveloper);
router.post('/:id/features', allow('admin'), c.addFeature);
router.patch('/:id/features/:featureId', allow('admin'), c.updateFeature);
router.delete('/:id/features/:featureId', allow('admin'), c.removeFeature);
router.post('/:id/versions', allow('admin'), c.saveVersion);
router.post('/:id/versions/:versionId/confirm', allow('admin'), c.confirmVersion);
router.post('/:id/discussions', c.addDiscussion);
router.post('/:id/quotation', allow('admin'), c.createAndSendQuotation);
module.exports = router;
